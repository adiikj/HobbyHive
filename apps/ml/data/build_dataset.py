def main() -> None:
    rows = [(text, label) for label, texts in POSTS.items() for text in texts]
    random.Random(42).shuffle(rows)
    out = Path(__file__).parent / "hobby_posts.csv"
    with out.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "label"])
        writer.writerows(rows)
    counts = {label: len(texts) for label, texts in POSTS.items()}
    print(f"wrote {len(rows)} rows to {out.name}: {counts}")


if __name__ == "__main__":
    main()
